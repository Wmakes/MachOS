#!/bin/sh
# regenerate userland/mach.toml's [artifact.*] tables, one per program in
# userland/src/bin (everything after the "# programs" marker)
set -eu
cd "$(dirname "$0")/../userland"
sed -i '/^# programs/,$d' mach.toml
sed -i -e :a -e '/^\n*$/{$d;N;ba' -e '}' mach.toml # trim trailing blank lines
printf '\n# programs (generated by tools/programs.sh)\n' >> mach.toml
for f in src/bin/*.mach; do
    name=$(basename "$f" .mach)
    cat >> mach.toml <<T

[artifact.$name]
kind = "bin"
entry = "bin/$name.mach"
out = "bin/$name"
targets = ["machos"]
link = []
need = []
T
done
