#!/bin/sh
# regenerate the [artifact.*] tables for every src/user/bin/*.mach program
# in mach.toml (everything after the "# user programs" marker)
set -eu
cd "$(dirname "$0")/.."
sed -i '/^# user programs/,$d' mach.toml
sed -i -e :a -e '/^\n*$/{$d;N;ba' -e '}' mach.toml # trim trailing blank lines
printf '\n# user programs (generated by tools/programs.sh)\n' >> mach.toml
for f in src/user/bin/*.mach; do
    name=$(basename "$f" .mach)
    cat >> mach.toml <<T

[artifact.$name]
kind = "bin"
entry = "user/bin/$name.mach"
out = "bin/$name"
targets = ["user"]
link = []
need = []
T
done
